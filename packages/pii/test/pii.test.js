// @ts-check
// 고유식별정보·식별값만 가린다. 이름·나이·주소는 그대로 (사용자 결정 11/17)
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { detectPii, mask } from '../index.js';

const m = (/** @type {string} */ t) => mask(t, detectPii(t));

test('고유식별정보: 외국인등록번호·여권번호(문맥)·운전면허번호', () => {
  assert.equal(m('외국인등록번호 900101-5123454'), '외국인등록번호 [외국인등록번호]');
  assert.equal(m('여권번호: M12345678, 여권 M123A4567'), '여권번호: [여권번호], 여권 [여권번호]');
  assert.equal(m('운전면허 11-12-123456-12 확인'), '운전면허 [운전면허번호] 확인');
  assert.equal(m('면허 서울 12-123456-12'), '면허 [운전면허번호]');
});

test('이름·나이·주소·날짜는 가리지 않음', () => {
  const t = '고객 홍길동(45세) 님, 서울특별시 중구 을지로 35, 시행일 2026-11-01';
  assert.equal(m(t), t);
});

test('IP 주소는 그대로 보인다 (사용자 결정 11/17 22시), 버전·날짜도 그대로', () => {
  const t = '장비 IP: 10.20.30.41 / IP는 10.100.64.95. / 버전 1.2.3, 시행 2026.11.17';
  assert.equal(m(t), t);
});

test('전화번호·이메일은 가리지 않고 계좌로도 오탐하지 않음 (사용자 결정 11/17 22시), 계좌는 그대로', () => {
  const t = '담당 010-1234-5678, 본점 02-123-4567, 지점 031-123-4567, 대표 1588-1111, hong@hana.example';
  assert.equal(m(t), t);
  assert.equal(m('입금 계좌번호: 110-123-456789'), '입금 계좌번호: [계좌번호]');
  assert.equal(m('참조 123-45-678901'), '참조 [계좌번호]');
});

test('OCR이 깨뜨린 날짜·버전 숫자(N-2-2)는 계좌로 오탐하지 않음 (과천 매뉴얼 실측), 실제 계좌 형태는 그대로', () => {
  const t = 'Scan Drive 202-06-21 171 / 3820-00-18 Hies / 200-00-15 / (64bit)/221.2/3002-16-06';
  assert.equal(m(t), t);
  assert.equal(m('참조 123-45-678901, 1002-123-456789'), '참조 [계좌번호], [계좌번호]');
});
